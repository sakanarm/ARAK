  // -------------------------------------------------------------- NL -> SQL

  /**
   * Turns a question into one SELECT statement.
   *
   * <p>The statement is a suggestion and is returned as text, not run. What
   * comes back has not touched a database.
   */
  @POST
  @Path("/sql")
  public SqlDraft sql(SqlAsk ask, @Context SecurityContext security) {
    if (ask == null || ask.question() == null || ask.question().isBlank()) {
      throw new BadRequestException("A question is required");
    }
    if (ask.sourceId() == null) {
      throw new BadRequestException("Choose a source first, so the tables can be looked up");
    }
    AuthenticatedUser actor = caller(security);
    EffectiveSetting mine = ready(actor, Feature.WRITE_SQL);

    List<AssistPrompts.Table> tables = tablesFor(ask.sourceId(), ask.question());
    if (tables.isEmpty()) {
      throw new BadRequestException(
          "Nothing has been crawled for this source yet, so there is no schema to write against");
    }
    String brief = AssistPrompts.schemaBrief(tables);

    String answer =
        ask(
            actor,
            mine,
            ask.model(),
            AssistPrompts.sqlSystem(ask.engine()),
            AssistPrompts.sqlUser(ask.question(), brief));
    return draftFrom(
        answer,
        chosenModel(ask.model(), mine),
        tables,
        mine.usingOwnGateway(),
        actor,
        "The assistant could not answer that from the tables in this source.");
  }

  // ------------------------------------------------------ fix and explain

  /**
   * Suggests a corrected statement for one that failed (M26).
   *
   * <p>The console offers this only when the statement itself was the problem
   * -- the refusal says {@code fixable} -- and never after a policy said no.
   * What comes back is a suggestion for the editor, exactly like a drafted
   * query: nothing is run here, and when the reader runs it, it goes through
   * the proxy and is enforced like anything else they type.
   */
  @POST
  @Path("/fix")
  public SqlDraft fix(FixAsk ask, @Context SecurityContext security) {
    String statement = statementOf(ask == null ? null : ask.sql());
    if (ask.sourceId() == null) {
      throw new BadRequestException("Choose a source first, so the tables can be looked up");
    }
    AuthenticatedUser actor = caller(security);
    EffectiveSetting mine = ready(actor, Feature.FIX_SQL);

    List<AssistPrompts.Table> tables = tablesFor(ask.sourceId(), statement);
    String brief = AssistPrompts.schemaBrief(tables);
    String error = AssistPrompts.redactError(ask.error(), statement, brief);

    String answer =
        ask(
            actor,
            mine,
            ask.model(),
            AssistPrompts.fixSystem(ask.engine()),
            AssistPrompts.fixUser(statement, error, brief));
    String model = chosenModel(ask.model(), mine);
    SqlDraft draft =
        draftFrom(
            answer,
            model,
            tables,
            mine.usingOwnGateway(),
            actor,
            "The assistant could not tell how to fix this statement from the tables in this"
                + " source.");
    if (draft.problem() == null && AssistPrompts.sameStatement(draft.sql(), statement)) {
      return new SqlDraft(
          "",
          model,
          draft.tables(),
          "The assistant did not find anything to change in this statement.",
          draft.personal());
    }
    return draft;
  }

  /**
   * Says what a statement does, in words (M26).
   *
   * <p>From the statement and the catalogue only. The model has not seen a
   * result and is told so, which is why the explanation is of what the
   * statement asks for rather than of what came back.
   */
  @POST
  @Path("/explain")
  public Explanation explain(ExplainAsk ask, @Context SecurityContext security) {
    String statement = statementOf(ask == null ? null : ask.sql());
    AuthenticatedUser actor = caller(security);
    EffectiveSetting mine = ready(actor, Feature.EXPLAIN_SQL);

    List<AssistPrompts.Table> tables =
        ask.sourceId() == null ? List.of() : tablesFor(ask.sourceId(), statement);
    String answer =
        ask(
            actor,
            mine,
            ask.model(),
            AssistPrompts.explainSystem(ask.engine()),
            AssistPrompts.explainUser(statement, AssistPrompts.schemaBrief(tables)));
    String text = AssistPrompts.extractExplanation(answer);
    if (text.isEmpty()) {
      throw new ServiceUnavailableException(
          "The assistant did not answer with an explanation. Try again in a moment.");
    }
    return new Explanation(
        text,
        chosenModel(ask.model(), mine),
        tables.stream().map(AssistPrompts.Table::fqn).toList(),
        mine.usingOwnGateway());
  }

  /**
   * Says what a policy does, in words (M15).
   *
   * <p>Open to whoever may read the policy, which is anybody signed in: the
   * policy page is. The model is told the document, where the policy is bound
   * and the verdicts the overlap screen already works out -- nothing from a
   * source database, and nobody's name from its exemptions or approvers. It
   * answers with text the page labels as its own; the Simulator, which runs the
   * engine, is what decides. Nothing here writes.
   */
  @POST
  @Path("/explain-policy")
  public PolicyExplanation explainPolicy(
      PolicyExplainAsk ask, @Context SecurityContext security) {
    if (ask == null || ask.policyId() == null) {
      throw new BadRequestException("Say which policy to explain");
    }
    AuthenticatedUser actor = caller(security);
    if (policyReading == null) {
      throw new NotFoundException("Explaining a policy is not available on this deployment");
    }
    EffectiveSetting mine = ready(actor, Feature.EXPLAIN_POLICY);

    PolicyStore.StoredPolicy policy =
        policyReading
            .policies()
            .find(ask.policyId())
            .orElseThrow(() -> new NotFoundException("No policy " + ask.policyId()));
    PolicyOverview.Coverage coverage = policyReading.overview().coverage(policy.id());
    List<PolicyOverview.Overlap> overlaps =
        policyReading.overview().overlaps(policy.id(), policy.document(), policy.environment());

    String answer =
        ask(
            actor,
            mine,
            ask.model(),
            AssistPrompts.explainPolicySystem(ask.language()),
            AssistPrompts.explainPolicyUser(factsOf(policy, coverage, overlaps)));
    String text = AssistPrompts.extractExplanation(answer);
    if (text.isEmpty()) {
      throw new ServiceUnavailableException(
          "The assistant did not answer with an explanation. Try again in a moment.");
    }
    return new PolicyExplanation(text, chosenModel(ask.model(), mine), mine.usingOwnGateway());
  }

  /**
   * Explain the dashboard (M15): what stands out, what is unusual, and what to
   * look at next.
   *
   * <p>The dashboard is read the way its page reads it, as the caller, so it is
   * refused to anybody the page refuses. The model is sent its counts with
   * every person the page names numbered instead ({@link DashboardBrief}); the
   * names go back into the answer here, for the person who asked, who could
   * already see them. No row, statement or client address is sent, and
   * nothing here writes.
   */
  @POST
  @Path("/explain-dashboard")
  public DashboardExplanation explainDashboard(
      DashboardExplainAsk ask, @Context SecurityContext security) {
    if (ask == null) {
      throw new BadRequestException("Say what to explain");
    }
    DashboardBrief.Focus focus;
    try {
      focus = DashboardBrief.Focus.parse(ask.focus());
    } catch (IllegalArgumentException e) {
      throw new BadRequestException(e.getMessage());
    }
    AuthenticatedUser actor = caller(security);
    if (dashboards == null) {
      throw new NotFoundException("Explaining the dashboard is not available on this deployment");
    }
    EffectiveSetting mine = ready(actor, Feature.EXPLAIN_DASHBOARD);

    DashboardResource.Dashboard dashboard =
        dashboards.dashboard(
            ask.days() == null ? 30 : ask.days(),
            ask.label() == null ? "PII" : ask.label(),
            security);
    DashboardBrief.Brief brief = DashboardBrief.of(dashboard, focus);

    String answer =
        ask(
            actor,
            mine,
            ask.model(),
            AssistPrompts.explainDashboardSystem(ask.language()),
            AssistPrompts.explainDashboardUser(brief.text()));
    String text = AssistPrompts.extractExplanation(answer);
    if (text.isEmpty()) {
      throw new ServiceUnavailableException(
          "The assistant did not answer with an explanation. Try again in a moment.");
    }
    return new DashboardExplanation(
        DashboardBrief.restorePeople(text, brief.people()),
        chosenModel(ask.model(), mine),
        mine.usingOwnGateway());
  }

  /** The policy as the model is told it: see {@link AssistPrompts#policyForExplaining}. */
  private AssistPrompts.PolicyFacts factsOf(
      PolicyStore.StoredPolicy policy,
      PolicyOverview.Coverage coverage,
      List<PolicyOverview.Overlap> overlaps) {
    String document;
    try {
      document =
          AssistPrompts.policyForExplaining(
              policyReading.json().writeValueAsString(policy.document()));
    } catch (JsonProcessingException | IllegalArgumentException e) {
      throw new BadRequestException(
          "This policy cannot be sent to the assistant: " + e.getMessage());
    }
    List<PolicyOverview.Target> sample =
        coverage.sample() == null ? List.of() : coverage.sample();
    List<String> targets =
        sample.stream()
            .limit(AssistPrompts.MAX_EXPLAIN_TARGETS)
            .map(
                t ->
                    (t.kind() == null ? "" : t.kind().toLowerCase(Locale.ROOT) + " ") + t.fqn())
            .toList();
    boolean more =
        coverage.truncated()
            || coverage.tableCount() + coverage.columnCount() > targets.size();
    List<AssistPrompts.Neighbour> neighbours =
        overlaps.stream()
            .limit(AssistPrompts.MAX_NEIGHBOURS)
            .map(
                o ->
                    new AssistPrompts.Neighbour(
                        o.displayName() != null && !o.displayName().isBlank()
                            ? o.displayName()
                            : o.name(),
                        o.scopeLevel(),
                        o.policyType(),
                        o.effect(),
                        o.lifecycleState(),
                        o.sharedTargets(),
                        o.relation(),
                        o.explanation(),
                        o.overrideNote()))
            .toList();
    return new AssistPrompts.PolicyFacts(
        document,
        policy.lifecycleState(),
        policy.environment(),
        coverage.tableCount(),
        coverage.columnCount(),
        targets,
        more,
        neighbours,
        overlaps.size());
  }

  /** The statement to fix or explain, or the reason it cannot be sent. */
  private static String statementOf(String sql) {
    if (sql == null || sql.isBlank()) {
      throw new BadRequestException("Write a statement first");
    }
    if (sql.length() > MAX_STATEMENT) {
      throw new BadRequestException(
          "This statement is too long to send to the assistant (the limit is "
              + MAX_STATEMENT
              + " characters)");
    }
    return sql.trim();
  }

  /**
   * An answer turned into something safe to put in the editor.
   *
   * <p>Shared by drafting and fixing, because the rule is the same for both: a
   * statement is only offered if it is one read-only query.
   */
  private SqlDraft draftFrom(
      String answer,
      String model,
      List<AssistPrompts.Table> tables,
      boolean personal,
      AuthenticatedUser actor,
      String unanswerable) {
    String sql = AssistPrompts.extractSql(answer);
    List<String> used = tables.stream().map(AssistPrompts.Table::fqn).toList();

    if (sql.isEmpty() || AssistPrompts.isRefusal(sql)) {
      return new SqlDraft("", model, used, unanswerable, personal);
    }
    if (!AssistPrompts.looksReadOnly(sql)) {
      // Not put in the editor at all. The proxy would refuse it, but a console
      // that offers a statement beside a Run button is making a suggestion, and
      // this is not one worth making.
      LOG.warn(
          "Discarded an assistant suggestion for {} that was not a read-only query",
          actor.username());
      return new SqlDraft(
          "",
          model,
          used,
          "The assistant answered with something that was not a read-only query, so it was"
              + " discarded.",
          personal);
    }
    return new SqlDraft(sql, model, used, null, personal);
  }

  // ---------------------------------------------------------- policy drafts

  /**
   * Turns a sentence into a draft policy document, or into a change to one.
   *
   * <p>Returned, never stored. The builder loads it as an unsaved form for
   * somebody to correct, and saving it is their act under their name — which is
   * the whole point of drafting rather than applying (FR-9.1).
   *
   * <p>With {@code current}, the sentence is a change to a policy that already
   * exists and the answer is that whole policy, changed. It is still only text:
   * the builder shows what changed and the policy stays as it is until somebody
   * saves it — which, for an active policy, is the moment it takes effect.
   */
  @POST
  @Path("/policy")
  public PolicyDraft policy(PolicyAsk ask, @Context SecurityContext security) {
    if (ask == null || ask.intent() == null || ask.intent().isBlank()) {
      throw new BadRequestException("Say what the policy should do");
    }
    String current = null;
    if (ask.current() != null) {
      try {
        current = AssistPrompts.policyForEdit(ask.current());
      } catch (IllegalArgumentException e) {
        throw new BadRequestException(e.getMessage());
      }
    }
    AuthenticatedUser actor = caller(security);
    EffectiveSetting mine = ready(actor, Feature.DRAFT_POLICY);
    String document =
        current == null
            ? draftDocument(actor, mine, ask.model(), ask.intent(), ask.sourceId())
            : editDocument(actor, mine, ask.model(), ask.intent(), current, ask.sourceId());
    return new PolicyDraft(document, chosenModel(ask.model(), mine), mine.usingOwnGateway());
  }

  /** A policy document from a sentence, or the reason there is none. Never stored. */
  private String draftDocument(
      AuthenticatedUser actor,
      EffectiveSetting mine,
      String model,
      String intent,
      UUID sourceId) {
    String brief =
        sourceId == null ? "" : AssistPrompts.schemaBrief(tablesFor(sourceId, intent));

    String answer =
        ask(
            actor,
            mine,
            model,
            AssistPrompts.policySystem(policySchemas()),
            AssistPrompts.policyUser(intent, brief));

    String document = AssistPrompts.extractJson(answer);
    if (document.isEmpty()) {
      throw new ServiceUnavailableException(
          "The assistant did not answer with a policy document. Try saying it a different way.");
    }
    return document;
  }

  /** The policy with the change made, or the reason there is none. Never stored. */
  private String editDocument(
      AuthenticatedUser actor,
      EffectiveSetting mine,
      String model,
      String intent,
      String current,
      UUID sourceId) {
    String brief =
        sourceId == null ? "" : AssistPrompts.schemaBrief(tablesFor(sourceId, intent));

    String answer =
        ask(
            actor,
            mine,
            model,
            AssistPrompts.policyEditSystem(policySchemas()),
            AssistPrompts.policyEditUser(intent, current, brief));

    String document = AssistPrompts.extractJson(answer);
    if (document.isEmpty()) {
      throw new ServiceUnavailableException(
          "The assistant did not answer with the changed policy. Try saying it a different way.");
    }
    return document;
  }

