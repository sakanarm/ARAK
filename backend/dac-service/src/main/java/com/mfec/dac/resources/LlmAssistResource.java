  /** The columns of one table to draft descriptions for, and the language to write them in. */
  public record DescribeAsk(String assetFqn, List<String> columns, String language, String model) {}

  /** Drafts for the columns the assistant could describe; the rest it left alone. */
  public record ColumnDrafts(
      List<AssistPrompts.ColumnDraft> drafts, String model, boolean personal) {}

  /** Columns per call. A wide table is drafted in several, so each answer stays short and quick. */
  static final int MAX_DESCRIBE = 40;

  /**
   * Drafts descriptions of a table's columns, for whoever governs it.
   *
   * <p>Returned, never stored: the table's page puts them in the form as
   * drafts, and a description exists only once that person has read it and
   * saved it under their own name. The model is given the table's metadata and
   * nothing else -- the same as every other job here.
   */
  @POST
  @Path("/describe-columns")
  public ColumnDrafts describeColumns(DescribeAsk ask, @Context SecurityContext security) {
    if (ask == null || ask.assetFqn() == null || ask.assetFqn().isBlank()) {
      throw new BadRequestException("Say which table the columns belong to");
    }
    if (ask.columns() == null || ask.columns().isEmpty()) {
      throw new BadRequestException("Say which columns to describe");
    }
    if (ask.columns().size() > MAX_DESCRIBE) {
      throw new BadRequestException("Ask for at most " + MAX_DESCRIBE + " columns at a time");
    }
    AuthenticatedUser actor = caller(security);
    String fqn = ask.assetFqn().trim();
    if (!Stewardship.governs(actor, fqn)) {
      throw new ForbiddenException(
          "You do not govern " + fqn + ", so you cannot describe its columns");
    }
    EffectiveSetting mine = ready(actor, Feature.DESCRIBE_COLUMNS);

    CatalogQuery.AssetDetail detail =
        catalog
            .asset(fqn)
            .filter(d -> Set.of("TABLE", "VIEW").contains(d.asset().assetType()))
            .orElseThrow(() -> new NotFoundException("No current table or view " + fqn));

    Map<String, CatalogQuery.ColumnDetail> byName = new LinkedHashMap<>();
    for (CatalogQuery.ColumnDetail column : detail.columns()) {
      byName.putIfAbsent(column.name().toLowerCase(Locale.ROOT), column);
    }
    Set<String> wanted = new LinkedHashSet<>();
    List<AssistPrompts.Column> toDescribe = new ArrayList<>();
    for (String name : ask.columns()) {
      CatalogQuery.ColumnDetail column =
          name == null ? null : byName.get(name.trim().toLowerCase(Locale.ROOT));
      if (column != null && wanted.add(column.name())) {
        toDescribe.add(
            new AssistPrompts.Column(
                column.name(), column.dataType(), column.description(), tagNames(column)));
      }
    }
    if (toDescribe.isEmpty()) {
      throw new BadRequestException("None of those are columns of " + fqn);
    }
    List<String> others = new ArrayList<>();
    for (CatalogQuery.ColumnDetail column : detail.columns()) {
      if (!wanted.contains(column.name())) {
        others.add(column.name());
      }
    }

    String answer =
        ask(
            actor,
            mine,
            ask.model(),
            AssistPrompts.describeColumnsSystem(ask.language()),
            AssistPrompts.describeColumnsUser(
                new AssistPrompts.Table(fqn, detail.asset().description(), List.of()),
                toDescribe,
                others));
    return new ColumnDrafts(
        AssistPrompts.extractColumnDrafts(answer, List.copyOf(wanted)),
        chosenModel(ask.model(), mine),
        mine.usingOwnGateway());
  }

  /** The jobs this caller is offered; every one when nobody has narrowed them. */
  private Set<Feature> allowed(AuthenticatedUser actor) {
    return features == null ? EnumSet.allOf(Feature.class) : features.allowedFor(actor);
  }

  // ----------------------------------------------------------------- helpers

  /**
   * The tables of one source, narrowed to the question.
   *
   * <p>Columns come from the asset detail rather than the summary, because the
   * summary carries a count and the model needs the names. That is one query
   * per table, which is why the count is capped before the loop and not after.
   */
  private List<AssistPrompts.Table> tablesFor(UUID sourceId, String question) {
    CatalogQuery.AssetPage page =
        catalog.assets(null, "TABLE", List.of(), null, sourceId, CANDIDATES, 0);

    List<AssistPrompts.Table> shallow = new ArrayList<>();
    for (CatalogQuery.AssetSummary asset : page.items()) {
      shallow.add(new AssistPrompts.Table(asset.fqn(), asset.description(), List.of()));
    }
    List<AssistPrompts.Table> chosen = AssistPrompts.mostRelevant(shallow, question, MAX_TABLES);

    List<AssistPrompts.Table> full = new ArrayList<>();
    for (AssistPrompts.Table table : chosen) {
      Optional<CatalogQuery.AssetDetail> detail = catalog.asset(table.fqn());
      if (detail.isEmpty()) {
        continue;
      }
      List<AssistPrompts.Column> columns = new ArrayList<>();
      for (CatalogQuery.ColumnDetail column : detail.get().columns()) {
        columns.add(
            new AssistPrompts.Column(
                column.name(), column.dataType(), column.description(), tagNames(column)));
      }
      full.add(new AssistPrompts.Table(table.fqn(), table.description(), columns));
    }
    return full;
  }

  /** The facet names on a column, deduplicated, for the brief. */
  private static List<String> tagNames(CatalogQuery.ColumnDetail column) {
    Set<String> names = new LinkedHashSet<>();
    if (column.facets() != null) {
      for (CatalogQuery.FacetRow facet : column.facets()) {
        names.add(facet.facetFqn());
      }
    }
    return List.copyOf(names);
  }

  /**
   * The policy JSON Schemas, handed to the model as the contract.
   *
   * <p>Read from the classpath rather than restated here, so the shape the
   * model is asked for is the same file the engine's classes are generated
   * from. A prose summary of a schema is a second source of truth and would be
   * the one that rots.
   *
   * <p>{@code type/facet.json} is sent too: the selector and every column rule
   * are {@code $ref}s into it. Without it the model saw a reference it could
   * not follow and invented a selector of its own ({@code {"tags": [...]}}),
   * which the builder has no field for, so the form opened with no condition.
   */
  static final List<String> POLICY_SCHEMAS =
      List.of(
          "entity/policy/policy.json",
          "entity/policy/subjectRule.json",
          "entity/policy/dataPolicy.json",
          "type/facet.json");

  private String policySchemas() {
    StringBuilder out = new StringBuilder();
    for (String name : POLICY_SCHEMAS) {
      String path = "json/schema/" + name;
      try (InputStream in = getClass().getClassLoader().getResourceAsStream(path)) {
        if (in == null) {
          LOG.warn("Policy schema {} is not on the classpath; drafting without it", path);
          continue;
        }
        out.append("// ").append(name).append('\n');
        out.append(new String(in.readAllBytes(), StandardCharsets.UTF_8).trim()).append("\n\n");
      } catch (IOException e) {
        LOG.warn("Could not read policy schema {}", path, e);
      }
    }
    return out.toString().trim();
  }

  /**
   * The caller's setting, or the reason they cannot use this.
   *
   * <p>Read from the store, never from the request: switching the assistant off
   * has to mean it is off, including for somebody who knows the URL of this
   * endpoint.
   */
  private EffectiveSetting ready(AuthenticatedUser actor, Feature feature) {
    EffectiveSetting mine = store.effectiveFor(actor.id());
    if (!mine.enabled()) {
      throw new ForbiddenException("The assistant is not switched on for this account");
    }
    if (!allowed(actor).contains(feature)) {
      throw new ForbiddenException(feature.label() + " is not offered to your role");
    }
    if (!mine.available()) {
      throw new ServiceUnavailableException(mine.problem());
    }
    return mine;
  }

  private String ask(
      AuthenticatedUser actor,
      EffectiveSetting mine,
      String requestedModel,
      String system,
      String user) {
    try {
      Gateway gateway = store.gatewayFor(actor.id());
      LlmClient.Completion answer =
          client.complete(gateway, chosenModel(requestedModel, mine), system, user);
      return answer.text() == null ? "" : answer.text();
    } catch (LlmClient.LlmException e) {
      throw new ServiceUnavailableException(e.getMessage());
    }
  }

  private static String chosenModel(String requested, EffectiveSetting mine) {
    return requested != null && !requested.isBlank()
        ? requested.trim()
        : mine.effectiveModel();
  }

  private static AuthenticatedUser caller(SecurityContext security) {
    if (security == null || !(security.getUserPrincipal() instanceof AuthenticatedUser user)) {
      throw new ForbiddenException("No caller on this request");
    }
    return user;
  }
